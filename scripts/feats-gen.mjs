// Writes the app's copy of the feat catalog from the catalog JSON of CONTRACTS.md ("The catalog in each repo"):
//   node scripts/feats-gen.mjs <feats.json>
// The input is the design's feats.json or the website's `php artisan feats:export`. Both carry the same fields; `was`,
// `facts` and `made_from` are dropped. Output: companion/src/feats_catalog.rs and app/ui/feats-catalog.js. Running it twice on
// one input changes nothing.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const at = args.indexOf("--crests");
const crestsFile = at < 0 ? null : args.splice(at, 2)[1];
const input = args[0];
if (!input) {
  console.error("usage: node scripts/feats-gen.mjs <feats.json> [--crests <crests.json>]");
  process.exit(2);
}
const REPO = path.resolve(import.meta.dirname, "..");
const source = JSON.parse(fs.readFileSync(input, "utf8"));
const crests = crestsFile ? JSON.parse(fs.readFileSync(crestsFile, "utf8")).feats : {};

const FEAT_FIELDS = ["key", "name", "family", "collection", "scope", "class", "tree", "role", "glyph", "icon", "one", "many", "unit", "thresholds", "economy", "measure", "spells", "live"];
const CREST_FIELDS = ["crest", "account", "account_thresholds"];
const crestOf = (f) => {
  const own = Object.fromEntries(CREST_FIELDS.filter((k) => f[k] !== undefined).map((k) => [k, f[k]]));
  const found = CREST_FIELDS.every((k) => k in own) ? own : { ...(crests[f.key] ?? {}), ...own };
  const missing = CREST_FIELDS.filter((k) => found[k] === undefined);
  if (missing.length) {
    console.error(`${f.key} has no ${missing.join(", ")}: add them to the catalog or pass --crests <crests.json>`);
    process.exit(1);
  }
  return found;
};
const catalog = {
  version: source.version,
  tiers: source.tiers,
  families: source.families,
  role_classes: source.role_classes,
  spec_roles: source.spec_roles,
  feats: source.feats.map((f) => ({
    ...Object.fromEntries(FEAT_FIELDS.filter((k) => f[k] !== undefined).map((k) => [k, f[k]])),
    ...crestOf(f),
  })),
};

const js = `${[
  "// Generated by scripts/feats-gen.mjs from the catalog JSON. Do not edit.",
  `export const CATALOG = {`,
  `  version: ${catalog.version},`,
  `  tiers: ${JSON.stringify(catalog.tiers)},`,
  `  families: ${JSON.stringify(catalog.families)},`,
  `  role_classes: ${JSON.stringify(catalog.role_classes)},`,
  `  spec_roles: ${JSON.stringify(catalog.spec_roles)},`,
  `  feats: [`,
  ...catalog.feats.map((f) => `    ${JSON.stringify(f)},`),
  `  ],`,
  `};`,
  ``,
  `export const BY_KEY = new Map(CATALOG.feats.map((f) => [f.key, f]));`,
].join("\n")}\n`;
fs.writeFileSync(path.join(REPO, "app/ui/feats-catalog.js"), js);

const str = (s) => JSON.stringify(s);
const opt = (v) => (v === undefined ? "None" : `Some(${str(v)})`);
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const optNum = (v) => (v === undefined ? "None" : `Some(${num(v)})`);
const list = (a) => `&[${(a ?? []).map(str).join(", ")}]`;

const feats = catalog.feats.map((f) => {
  const live = f.live
    ? `Some(Live { kind: ${str(f.live.kind)}, keys: ${list(f.live.keys)}, per: ${optNum(f.live.per)}, once_at: ${optNum(f.live.once_at)}, gate: ${opt(f.live.gate)} })`
    : "None";
  return `    CatalogFeat { key: ${str(f.key)}, name: ${str(f.name)}, family: ${str(f.family)}, collection: ${str(f.collection)}, scope: ${str(f.scope)}, class: ${opt(f.class)}, tree: ${opt(f.tree)}, role: ${opt(f.role)}, glyph: ${str(f.glyph)}, one: ${str(f.one)}, many: ${str(f.many)}, unit: ${opt(f.unit)}, thresholds: [${f.thresholds.map(num).join(", ")}], crest: ${str(f.crest)}, account: ${str(f.account)}, account_thresholds: ${f.account_thresholds ? `Some([${f.account_thresholds.map(num).join(", ")}])` : "None"}, economy: ${Boolean(f.economy)}, measure: ${opt(f.measure)}, spells: ${list(f.spells)}, live: ${live} },`;
});

const specRoles = Object.entries(catalog.spec_roles).map(
  ([cls, trees]) => `    (${str(cls)}, &[${Object.entries(trees).map(([tree, roles]) => `(${str(tree)}, ${list(roles)})`).join(", ")}]),`,
);
const roleClasses = Object.entries(catalog.role_classes).map(([role, classes]) => `    (${str(role)}, ${list(classes)}),`);

const rs = `//! Generated by scripts/feats-gen.mjs from the catalog JSON. Do not edit.

pub const VERSION: u32 = ${catalog.version};

pub struct Live {
    pub kind: &'static str,
    pub keys: &'static [&'static str],
    pub per: Option<f64>,
    pub once_at: Option<f64>,
    pub gate: Option<&'static str>,
}

pub struct CatalogFeat {
    pub key: &'static str,
    pub name: &'static str,
    pub family: &'static str,
    pub collection: &'static str,
    pub scope: &'static str,
    pub class: Option<&'static str>,
    pub tree: Option<&'static str>,
    pub role: Option<&'static str>,
    pub glyph: &'static str,
    pub one: &'static str,
    pub many: &'static str,
    pub unit: Option<&'static str>,
    pub thresholds: [f64; 5],
    pub crest: &'static str,
    pub account: &'static str,
    pub account_thresholds: Option<[f64; 5]>,
    pub economy: bool,
    pub measure: Option<&'static str>,
    pub spells: &'static [&'static str],
    pub live: Option<Live>,
}

pub const TIERS: [&str; 5] = ${JSON.stringify(catalog.tiers)};

pub type Named = (&'static str, &'static [&'static str]);
pub type Nested = (&'static str, &'static [Named]);

pub static SPEC_ROLES: &[Nested] = &[
${specRoles.join("\n")}
];

pub static ROLE_CLASSES: &[Named] = &[
${roleClasses.join("\n")}
];

pub static FEATS: &[CatalogFeat] = &[
${feats.join("\n")}
];
`;
const target = path.join(REPO, "companion/src/feats_catalog.rs");
fs.writeFileSync(target, rs);
const fmt = spawnSync("rustfmt", ["--edition", "2024", target], { encoding: "utf8" });
if (fmt.status !== 0) console.error(`rustfmt did not run: ${fmt.stderr || fmt.error}`);
console.log(`catalog ${catalog.version}: ${catalog.feats.length} feats -> companion/src/feats_catalog.rs, app/ui/feats-catalog.js`);
