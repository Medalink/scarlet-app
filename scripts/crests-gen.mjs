// Writes the app's copy of the crest art from the crest kit (scarlet-web resources/crests/kit.json):
//   node scripts/crests-gen.mjs [--kit <kit.json>]
// Without --kit it reads the kit of the scarlet-web checkout beside this repo. Output: app/ui/crest-kit.js, which
// crests.js and tiers.js import. Running it twice on one kit changes nothing.
import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

const REPO = path.resolve(import.meta.dirname, "..");
const { values } = parseArgs({ options: { kit: { type: "string" } } });
const input = values.kit ?? path.join(REPO, "..", "scarlet-web", "resources", "crests", "kit.json");
if (!fs.existsSync(input)) {
  console.error(`no crest kit at ${input}\nusage: node scripts/crests-gen.mjs [--kit <kit.json>]`);
  process.exit(2);
}
const kit = JSON.parse(fs.readFileSync(input, "utf8"));

const EXPORTS = [
  ["BOX", "box"],
  ["CENTER", "center"],
  ["VIEW_BOX", "viewBox"],
  ["TIER_NAMES", "tierNames"],
  ["ATTACHES", "attaches"],
  ["SCOPES", "scopes"],
  ["QUALITY", "quality"],
  ["MATERIAL", "material"],
  ["BAND", "band"],
  ["GEM", "gem"],
  ["INK", "ink"],
  ["LIGHT", "light"],
  ["NEAR_AT", "nearAt"],
  ["UNEARNED", "unearned"],
  ["GLYPH_SIZE", "glyphSize"],
  ["PIECES", "pieces"],
];
const missing = EXPORTS.map(([, key]) => key).filter((key) => kit[key] === undefined);
if (missing.length) {
  console.error(`${input} has no ${missing.join(", ")}: the kit must carry them`);
  process.exit(1);
}

const isRecord = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const flat = (v) => JSON.stringify(v);
const body = (value) => {
  if (Array.isArray(value) && value.some(isRecord)) return `[\n${value.map((row) => `  ${flat(row)},`).join("\n")}\n]`;
  if (isRecord(value) && Object.values(value).some(isRecord)) return `{\n${Object.entries(value).map(([k, v]) => `  ${JSON.stringify(k)}: ${flat(v)},`).join("\n")}\n}`;
  return flat(value);
};

const js = `${["// Generated by scripts/crests-gen.mjs from the crest kit. Do not edit.", ...EXPORTS.map(([name, key]) => `export const ${name} = ${body(kit[key])};`)].join("\n")}\n`;
const target = path.join(REPO, "app/ui/crest-kit.js");
fs.writeFileSync(target, js);
console.log(`crest kit ${kit.version}: ${Object.keys(kit.pieces).length} pieces, ${kit.quality.length} tiers -> app/ui/crest-kit.js`);
